# ???????????????????????????????????????????????????????????????????
# SCRIPT DE VERIFICACIÓN: GAME MODE TWEAKS
# ???????????????????????????????????????????????????????????????????

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? VERIFICACIÓN GAME MODE TWEAKS" -ForegroundColor Green
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Verificar permisos de administrador
$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

if (-not $isAdmin) {
    Write-Host "??  ADVERTENCIA: Se recomienda ejecutar como Administrador" -ForegroundColor Yellow
    Write-Host "   (Algunas verificaciones pueden fallar sin permisos elevados)" -ForegroundColor Gray
    Write-Host ""
}

# ???????????????????????????????????????????????????????????????????
# 1. VERIFICAR WINDOWS GAME MODE
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? WINDOWS GAME MODE" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

try {
    $gameModeKey = "HKCU:\SOFTWARE\Microsoft\GameBar"
    
    if (Test-Path $gameModeKey) {
        $autoGameMode = Get-ItemProperty -Path $gameModeKey -Name "AutoGameModeEnabled" -ErrorAction SilentlyContinue
        $allowGameMode = Get-ItemProperty -Path $gameModeKey -Name "AllowAutoGameMode" -ErrorAction SilentlyContinue
        
        if ($autoGameMode -and $allowGameMode) {
            if ($autoGameMode.AutoGameModeEnabled -eq 1 -and $allowGameMode.AllowAutoGameMode -eq 1) {
                Write-Host "   ? Windows Game Mode: HABILITADO" -ForegroundColor Green
            } else {
                Write-Host "   ? Windows Game Mode: DESHABILITADO" -ForegroundColor Red
            }
            
            Write-Host "      AutoGameModeEnabled: $($autoGameMode.AutoGameModeEnabled)" -ForegroundColor Gray
            Write-Host "      AllowAutoGameMode: $($allowGameMode.AllowAutoGameMode)" -ForegroundColor Gray
        } else {
            Write-Host "   ??  Windows Game Mode: NO CONFIGURADO" -ForegroundColor Yellow
        }
    } else {
        Write-Host "   ? Registry key no encontrada" -ForegroundColor Red
        Write-Host "      (¿Xbox Game Bar está instalado?)" -ForegroundColor Gray
    }
} catch {
    Write-Host "   ? Error al verificar Game Mode: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 2. VERIFICAR NTFS LAST ACCESS TIME
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? NTFS LAST ACCESS TIME" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

try {
    $ntfsResult = fsutil behavior query disablelastaccess 2>&1
    
    if ($ntfsResult -match "disablelastaccess = 1") {
        Write-Host "   ? NTFS Last Access: DESHABILITADO (OPTIMIZADO)" -ForegroundColor Green
        Write-Host "      Estado: Rendimiento de disco mejorado" -ForegroundColor Gray
    } elseif ($ntfsResult -match "disablelastaccess = 0") {
        Write-Host "   ??  NTFS Last Access: HABILITADO (DEFAULT)" -ForegroundColor Yellow
        Write-Host "      Estado: Se registra último acceso a archivos" -ForegroundColor Gray
    } elseif ($ntfsResult -match "disablelastaccess = 3") {
        Write-Host "   ??  NTFS Last Access: MODO HÍBRIDO (Windows 10+)" -ForegroundColor Cyan
        Write-Host "      Estado: Deshabilitado para system volume, habilitado para otros" -ForegroundColor Gray
    } else {
        Write-Host "   ??  NTFS Last Access: ESTADO DESCONOCIDO" -ForegroundColor Yellow
        Write-Host "      Resultado: $ntfsResult" -ForegroundColor Gray
    }
} catch {
    Write-Host "   ? Error al verificar NTFS: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 3. VERIFICAR GAME PROCESS PRIORITY
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? GAME PROCESS PRIORITY" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$gameExecutables = @(
    "FortniteClient-Win64-Shipping.exe",
    "cs2.exe",
    "VALORANT-Win64-Shipping.exe",
    "RainbowSix.exe",
    "Overwatch.exe",
    "ApexLegends.exe",
    "ModernWarfare.exe",
    "Warzone.exe",
    "LeagueofLegends.exe",
    "EscapeFromTarkov.exe"
)

$configuredCount = 0
$totalGames = $gameExecutables.Count

foreach ($exe in $gameExecutables) {
    $keyPath = "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options\$exe\PerfOptions"
    
    if (Test-Path $keyPath) {
        try {
            $perfOptions = Get-ItemProperty -Path $keyPath -ErrorAction SilentlyContinue
            
            if ($perfOptions) {
                $cpuPriority = $perfOptions.CpuPriorityClass
                $ioPriority = $perfOptions.IoPriority
                
                Write-Host "   ? $exe" -ForegroundColor Green
                Write-Host "      CPU Priority: $cpuPriority (3 = High)" -ForegroundColor Gray
                Write-Host "      IO Priority: $ioPriority (3 = High)" -ForegroundColor Gray
                Write-Host ""
                
                $configuredCount++
            }
        } catch {
            # Skip
        }
    }
}

if ($configuredCount -eq 0) {
    Write-Host "   ??  No hay juegos configurados con prioridad alta" -ForegroundColor Yellow
    Write-Host "      Estado: Configuración por defecto de Windows" -ForegroundColor Gray
} else {
    Write-Host "   ?? RESUMEN:" -ForegroundColor Cyan
    Write-Host "      Juegos configurados: $configuredCount / $totalGames" -ForegroundColor White
    Write-Host "      Porcentaje: $([math]::Round($configuredCount / $totalGames * 100, 1))%" -ForegroundColor White
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 4. VERIFICAR TRANSPARENCY
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? TRANSPARENCY EFFECTS" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

try {
    $transparencyKey = "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Themes\Personalize"
    
    if (Test-Path $transparencyKey) {
        $transparency = Get-ItemProperty -Path $transparencyKey -Name "EnableTransparency" -ErrorAction SilentlyContinue
        
        if ($transparency) {
            if ($transparency.EnableTransparency -eq 0) {
                Write-Host "   ? Transparency: DESHABILITADA (OPTIMIZADO)" -ForegroundColor Green
                Write-Host "      Estado: GPU dedicada 100% al juego" -ForegroundColor Gray
            } else {
                Write-Host "   ??  Transparency: HABILITADA (DEFAULT)" -ForegroundColor Yellow
                Write-Host "      Estado: Efectos visuales activos" -ForegroundColor Gray
            }
            
            Write-Host "      EnableTransparency: $($transparency.EnableTransparency)" -ForegroundColor Gray
        } else {
            Write-Host "   ??  Transparency: NO CONFIGURADO" -ForegroundColor Yellow
        }
    } else {
        Write-Host "   ? Registry key no encontrada" -ForegroundColor Red
    }
} catch {
    Write-Host "   ? Error al verificar Transparency: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# RESUMEN GENERAL
# ???????????????????????????????????????????????????????????????????

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? RESUMEN DE VERIFICACIÓN" -ForegroundColor Green
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Calcular estadísticas
$totalTweaks = 4
$activeTweaks = 0

# Game Mode
try {
    $gm = Get-ItemProperty -Path "HKCU:\SOFTWARE\Microsoft\GameBar" -Name "AutoGameModeEnabled" -ErrorAction SilentlyContinue
    if ($gm -and $gm.AutoGameModeEnabled -eq 1) { $activeTweaks++ }
} catch {}

# NTFS
try {
    $ntfs = fsutil behavior query disablelastaccess 2>&1
    if ($ntfs -match "disablelastaccess = 1") { $activeTweaks++ }
} catch {}

# Game Priority
if ($configuredCount -gt 0) { $activeTweaks++ }

# Transparency
try {
    $trans = Get-ItemProperty -Path "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Themes\Personalize" -Name "EnableTransparency" -ErrorAction SilentlyContinue
    if ($trans -and $trans.EnableTransparency -eq 0) { $activeTweaks++ }
} catch {}

Write-Host "Tweaks Activos: $activeTweaks / $totalTweaks" -ForegroundColor White
Write-Host "Porcentaje: $([math]::Round($activeTweaks / $totalTweaks * 100, 1))%" -ForegroundColor White
Write-Host ""

if ($activeTweaks -eq $totalTweaks) {
    Write-Host "? TODAS LAS OPTIMIZACIONES ESTÁN ACTIVAS" -ForegroundColor Green
} elseif ($activeTweaks -gt 0) {
    Write-Host "??  OPTIMIZACIÓN PARCIAL" -ForegroundColor Yellow
    Write-Host "   Considera activar los tweaks restantes desde Tweaker" -ForegroundColor Gray
} else {
    Write-Host "? NO HAY OPTIMIZACIONES ACTIVAS" -ForegroundColor Red
    Write-Host "   Ejecuta Tweaker para aplicar optimizaciones" -ForegroundColor Gray
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# RECOMENDACIONES
# ???????????????????????????????????????????????????????????????????

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? RECOMENDACIONES" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

if ($activeTweaks -lt $totalTweaks) {
    Write-Host "Para activar optimizaciones:" -ForegroundColor White
    Write-Host "  1. Abre Tweaker.exe (como Administrador)" -ForegroundColor Gray
    Write-Host "  2. Ve a 'Sistema & GPU'" -ForegroundColor Gray
    Write-Host "  3. Activa los tweaks de Game Mode" -ForegroundColor Gray
    Write-Host "  4. Reinicia Windows" -ForegroundColor Gray
    Write-Host ""
}

Write-Host "Tweaks recomendados para gaming:" -ForegroundColor White
Write-Host "  ? Windows Game Mode: ON" -ForegroundColor Gray
Write-Host "  ? NTFS Last Access: OFF (Deshabilitar)" -ForegroundColor Gray
Write-Host "  ? Game Priority: ON" -ForegroundColor Gray
Write-Host "  ? Transparency: OFF (Deshabilitar)" -ForegroundColor Gray
Write-Host ""

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

pause
