Write-Host "  ?? FIX FORTNITE HIGH PING" -ForegroundColor Green
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Verificar permisos de administrador
$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

if (-not $isAdmin) {
    Write-Host "? ERROR: Este script necesita permisos de Administrador" -ForegroundColor Red
    Write-Host "   Click derecho > Ejecutar como Administrador" -ForegroundColor Yellow
    Write-Host ""
    Read-Host "Presiona Enter para salir"
    exit
}

Write-Host "? Ejecutando como Administrador" -ForegroundColor Green
Write-Host ""

# ???????????????????????????????????????????????????????????????
# PASO 1: REVERTIR TWEAKS TCP/IP (CAUSA MÁS COMÚN)
# ???????????????????????????????????????????????????????????????

Write-Host "?? PASO 1: REVIRTIENDO TWEAKS TCP/IP" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray
Write-Host ""

# Obtener todas las interfaces de red
$interfaces = Get-NetAdapter | Where-Object { $_.Status -eq "Up" }

if ($interfaces.Count -eq 0) {
    Write-Host "? No se encontraron interfaces de red activas" -ForegroundColor Red
    exit
}

Write-Host "Interfaces encontradas:" -ForegroundColor Cyan
foreach ($interface in $interfaces) {
    Write-Host "  • $($interface.Name) ($($interface.InterfaceDescription))" -ForegroundColor Gray
}
Write-Host ""

$revertCount = 0
$totalInterfaces = 0

foreach ($interface in $interfaces) {
    $totalInterfaces++
    $interfaceGuid = $interface.InterfaceGuid
    $path = "HKLM:\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\$interfaceGuid"
    
    Write-Host "Procesando: $($interface.Name)..." -ForegroundColor Cyan
    
    if (Test-Path $path) {
        try {
            # Eliminar TcpAckFrequency
            Remove-ItemProperty -Path $path -Name "TcpAckFrequency" -ErrorAction SilentlyContinue
            Remove-ItemProperty -Path $path -Name "TCPNoDelay" -ErrorAction SilentlyContinue
            Remove-ItemProperty -Path $path -Name "TcpDelAckTicks" -ErrorAction SilentlyContinue
            
            Write-Host "  ? Tweaks TCP/IP eliminados" -ForegroundColor Green
            $revertCount++
        } catch {
            Write-Host "  ?? Error al revertir: $($_.Exception.Message)" -ForegroundColor Yellow
        }
    }
}

Write-Host ""
Write-Host "? Interfaces procesadas: $revertCount/$totalInterfaces" -ForegroundColor Green
Write-Host ""

# ???????????????????????????????????????????????????????????????
# PASO 2: RESTAURAR CONFIGURACIÓN GLOBAL
# ???????????????????????????????????????????????????????????????

Write-Host "?? PASO 2: RESTAURANDO CONFIGURACIÓN GLOBAL" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray
Write-Host ""

$globalPath = "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Multimedia\SystemProfile"

try {
    Set-ItemProperty -Path $globalPath -Name "NetworkThrottlingIndex" -Value 10 -Type DWord
    Write-Host "? NetworkThrottlingIndex = 10 (default)" -ForegroundColor Green
} catch {
    Write-Host "?? Error al restaurar NetworkThrottlingIndex" -ForegroundColor Yellow
}

try {
    Set-ItemProperty -Path $globalPath -Name "SystemResponsiveness" -Value 20 -Type DWord
    Write-Host "? SystemResponsiveness = 20 (default)" -ForegroundColor Green
} catch {
    Write-Host "?? Error al restaurar SystemResponsiveness" -ForegroundColor Yellow
}

Write-Host ""

# ???????????????????????????????????????????????????????????????
# PASO 3: RESTAURAR MTU A DEFAULT
# ???????????????????????????????????????????????????????????????

Write-Host "?? PASO 3: RESTAURANDO MTU A DEFAULT" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray
Write-Host ""

foreach ($interface in $interfaces) {
    try {
        netsh interface ipv4 set subinterface "$($interface.Name)" mtu=1500 store=persistent | Out-Null
        Write-Host "? MTU restaurado a 1500 en: $($interface.Name)" -ForegroundColor Green
    } catch {
        Write-Host "?? Error al restaurar MTU en: $($interface.Name)" -ForegroundColor Yellow
    }
}

Write-Host ""

# ???????????????????????????????????????????????????????????????
# PASO 4: FLUSH DNS Y RESET WINSOCK
# ???????????????????????????????????????????????????????????????

Write-Host "?? PASO 4: LIMPIEZA DE RED" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray
Write-Host ""

Write-Host "Ejecutando comandos de limpieza..." -ForegroundColor Cyan

# Flush DNS
ipconfig /flushdns | Out-Null
Write-Host "? DNS Cache limpiado" -ForegroundColor Green

# Reset Winsock
netsh winsock reset | Out-Null
Write-Host "? Winsock reseteado" -ForegroundColor Green

# Reset IP
netsh int ip reset | Out-Null
Write-Host "? TCP/IP Stack reseteado" -ForegroundColor Green

Write-Host ""

# ???????????????????????????????????????????????????????????????
# PASO 5: TEST DE PING A SERVIDORES DE FORTNITE
# ???????????????????????????????????????????????????????????????

Write-Host "?? PASO 5: TEST DE PING A FORTNITE" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray
Write-Host ""

$fortniteServers = @(
    "qosping-aws-us-east-1.ol.epicgames.com",
    "qosping-aws-us-west-2.ol.epicgames.com",
    "qosping-aws-eu-west-1.ol.epicgames.com",
    "qosping-aws-sa-east-1.ol.epicgames.com"
)

Write-Host "Testeando servidores de Fortnite..." -ForegroundColor Cyan
Write-Host ""

foreach ($server in $fortniteServers) {
    $region = switch -Wildcard ($server) {
        "*us-east*" { "???? US East (NAE)" }
        "*us-west*" { "???? US West (NAW)" }
        "*eu-west*" { "???? Europe (EU)" }
        "*sa-east*" { "???? South America (BR)" }
    }
    
    Write-Host "$region" -ForegroundColor White
    
    try {
        $ping = Test-Connection -ComputerName $server -Count 4 -ErrorAction SilentlyContinue
        
        if ($ping) {
            $avgPing = [math]::Round(($ping | Measure-Object -Property ResponseTime -Average).Average, 0)
            
            if ($avgPing -lt 30) {
                Write-Host "  ? Ping promedio: $avgPing ms (EXCELENTE)" -ForegroundColor Green
            } elseif ($avgPing -lt 60) {
                Write-Host "  ? Ping promedio: $avgPing ms (BUENO)" -ForegroundColor Cyan
            } elseif ($avgPing -lt 100) {
                Write-Host "  ?? Ping promedio: $avgPing ms (ACEPTABLE)" -ForegroundColor Yellow
            } else {
                Write-Host "  ? Ping promedio: $avgPing ms (ALTO)" -ForegroundColor Red
            }
        } else {
            Write-Host "  ? No se pudo alcanzar servidor" -ForegroundColor Red
        }
    } catch {
        Write-Host "  ? Error al testear servidor" -ForegroundColor Red
    }
    
    Write-Host ""
}

