# Función para verificar valor de registry
function Test-RegistryValue {
    param(
        [string]$Path,
        [string]$Name,
        $ExpectedValue,
        [string]$Description
    )
    
    try {
        $value = Get-ItemProperty -Path $Path -Name $Name -ErrorAction SilentlyContinue
        
        if ($null -eq $value) {
            Write-Host "  ? $Description : NO EXISTE" -ForegroundColor $ColorError
            return $false
        }
        
        $actualValue = $value.$Name
        
        if ($actualValue -eq $ExpectedValue) {
            Write-Host "  ? $Description : $actualValue (CORRECTO)" -ForegroundColor $ColorSuccess
            return $true
        } else {
            Write-Host "  ??  $Description : $actualValue (esperado: $ExpectedValue)" -ForegroundColor $ColorWarning
            return $false
        }
    }
    catch {
        Write-Host "  ? $Description : ERROR - $($_.Exception.Message)" -ForegroundColor $ColorError
        return $false
    }
}

# Función para verificar servicio
function Test-ServiceStatus {
    param(
        [string]$ServiceName,
        [string]$ExpectedStatus,
        [string]$ExpectedStartType
    )
    
    try {
        $service = Get-Service -Name $ServiceName -ErrorAction Stop
        
        $statusMatch = $service.Status -eq $ExpectedStatus
        $startTypeMatch = $service.StartType -eq $ExpectedStartType
        
        $color = if ($statusMatch -and $startTypeMatch) { $ColorSuccess } else { $ColorWarning }
        
        Write-Host "  $ServiceName :" -NoNewline
        Write-Host " Status=$($service.Status)" -NoNewline -ForegroundColor $color
        Write-Host " / StartType=$($service.StartType)" -ForegroundColor $color
        
        return ($statusMatch -and $startTypeMatch)
    }
    catch {
        Write-Host "  ? $ServiceName : NO ENCONTRADO" -ForegroundColor $ColorError
        return $false
    }
}

