$foundOptimized = $false
foreach ($interface in $interfaces) {
    $ackFreq = Get-ItemProperty -Path $interface.PSPath -Name "TcpAckFrequency" -ErrorAction SilentlyContinue
    if ($null -ne $ackFreq) {
        if ($ackFreq.TcpAckFrequency -eq 1) {
            Write-Host "  ? Interfaz optimizada encontrada: $($interface.PSChildName)" -ForegroundColor $ColorSuccess
            $foundOptimized = $true
        }
    }
}
if (-not $foundOptimized) {
    Write-Host "  ??  No se encontraron interfaces con TcpAckFrequency = 1" -ForegroundColor $ColorWarning
