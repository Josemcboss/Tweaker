Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? DIAGNÓSTICO DE PING DE FORTNITE" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Verificar si se ejecuta como administrador
$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    Write-Host "? Este script requiere permisos de Administrador" -ForegroundColor Red
    Write-Host "   Click derecho > Ejecutar como Administrador" -ForegroundColor Yellow
    pause
    exit
}

Write-Host "? Ejecutando como Administrador" -ForegroundColor Green
Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 1. VERIFICAR TWEAKS DE RED ACTIVOS
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? TWEAKS DE RED ACTIVOS" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Obtener interfaz activa
$adapter = Get-NetAdapter | Where-Object { $_.Status -eq "Up" -and $_.InterfaceDescription -notlike "*Virtual*" -and $_.InterfaceDescription -notlike "*Loopback*" } | Select-Object -First 1

if ($adapter) {
    Write-Host "?? Adaptador de Red Activo:" -ForegroundColor Green
    Write-Host "   Nombre: $($adapter.Name)" -ForegroundColor White
    Write-Host "   Descripción: $($adapter.InterfaceDescription)" -ForegroundColor White
    Write-Host "   GUID: $($adapter.InterfaceGuid)" -ForegroundColor White
    Write-Host ""
    
    # Verificar TcpAckFrequency
    $interfacePath = "HKLM:\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\$($adapter.InterfaceGuid)"
    
    Write-Host "?? TWEAKS APLICADOS:" -ForegroundColor Yellow
    
    # TcpAckFrequency
    $tcpAckFreq = Get-ItemProperty -Path $interfacePath -Name "TcpAckFrequency" -ErrorAction SilentlyContinue
    if ($tcpAckFreq) {
        Write-Host "   ??  TcpAckFrequency: $($tcpAckFreq.TcpAckFrequency)" -ForegroundColor Yellow
        Write-Host "      (Esto puede causar problemas de ping en algunas redes)" -ForegroundColor Gray
    } else {
        Write-Host "   ? TcpAckFrequency: No configurado (DEFAULT)" -ForegroundColor Green
    }
    
    # TCPNoDelay
    $tcpNoDelay = Get-ItemProperty -Path $interfacePath -Name "TCPNoDelay" -ErrorAction SilentlyContinue
    if ($tcpNoDelay) {
        Write-Host "   ??  TCPNoDelay: $($tcpNoDelay.TCPNoDelay)" -ForegroundColor Yellow
    } else {
        Write-Host "   ? TCPNoDelay: No configurado (DEFAULT)" -ForegroundColor Green
    }
    
    # TcpDelAckTicks
    $delAckTicks = Get-ItemProperty -Path $interfacePath -Name "TcpDelAckTicks" -ErrorAction SilentlyContinue
    if ($delAckTicks) {
        Write-Host "   ??  TcpDelAckTicks: $($delAckTicks.TcpDelAckTicks)" -ForegroundColor Yellow
    } else {
        Write-Host "   ? TcpDelAckTicks: No configurado (DEFAULT)" -ForegroundColor Green
    }
    
    Write-Host ""
} else {
    Write-Host "? No se encontró adaptador de red activo" -ForegroundColor Red
    Write-Host ""
}

# ???????????????????????????????????????????????????????????????????
# 2. VERIFICAR TWEAKS GLOBALES
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? TWEAKS GLOBALES DEL SISTEMA" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# NetworkThrottlingIndex
$throttling = Get-ItemProperty -Path "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Multimedia\SystemProfile" -Name "NetworkThrottlingIndex" -ErrorAction SilentlyContinue
if ($throttling -and $throttling.NetworkThrottlingIndex -eq 0xFFFFFFFF) {
    Write-Host "   ??  NetworkThrottlingIndex: FFFFFFFF (DESHABILITADO)" -ForegroundColor Yellow
    Write-Host "      (Puede causar problemas en redes inestables)" -ForegroundColor Gray
} else {
    Write-Host "   ? NetworkThrottlingIndex: DEFAULT" -ForegroundColor Green
}

# SystemResponsiveness
$responsiveness = Get-ItemProperty -Path "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Multimedia\SystemProfile" -Name "SystemResponsiveness" -ErrorAction SilentlyContinue
if ($responsiveness -and $responsiveness.SystemResponsiveness -eq 0) {
    Write-Host "   ??  SystemResponsiveness: 0 (TODO al gaming)" -ForegroundColor Yellow
} else {
    Write-Host "   ? SystemResponsiveness: DEFAULT (20)" -ForegroundColor Green
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 3. VERIFICAR MTU
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? CONFIGURACIÓN DE MTU" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

if ($adapter) {
    $mtu = Get-NetIPInterface -InterfaceIndex $adapter.ifIndex -AddressFamily IPv4 | Select-Object -ExpandProperty NlMtu
    Write-Host "   MTU Actual: $mtu bytes" -ForegroundColor White
    
    if ($mtu -eq 1492) {
        Write-Host "   ??  MTU modificado a 1492 (para PPPoE)" -ForegroundColor Yellow
        Write-Host "      Si no usas PPPoE, esto puede causar problemas" -ForegroundColor Gray
    } elseif ($mtu -eq 1500) {
        Write-Host "   ? MTU en 1500 (ESTÁNDAR)" -ForegroundColor Green
    } else {
        Write-Host "   ??  MTU no estándar: $mtu" -ForegroundColor Yellow
    }
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 4. VERIFICAR DNS
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? CONFIGURACIÓN DE DNS" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

if ($adapter) {
    $dnsServers = Get-DnsClientServerAddress -InterfaceIndex $adapter.ifIndex -AddressFamily IPv4 | Select-Object -ExpandProperty ServerAddresses
    
    if ($dnsServers) {
        Write-Host "   DNS Configurados:" -ForegroundColor White
        foreach ($dns in $dnsServers) {
            Write-Host "      - $dns" -ForegroundColor White
            
            # Identificar el DNS
            if ($dns -eq "1.1.1.1" -or $dns -eq "1.0.0.1") {
                Write-Host "        (Cloudflare DNS)" -ForegroundColor Gray
            } elseif ($dns -eq "8.8.8.8" -or $dns -eq "8.8.4.4") {
                Write-Host "        (Google DNS)" -ForegroundColor Gray
            }
        }
        
        # Test de latencia a DNS
        Write-Host ""
        Write-Host "   ?? Latencia a DNS:" -ForegroundColor Yellow
        foreach ($dns in $dnsServers) {
            $ping = Test-Connection -ComputerName $dns -Count 4 -Quiet -ErrorAction SilentlyContinue
            if ($ping) {
                $latency = (Test-Connection -ComputerName $dns -Count 4 | Measure-Object -Property ResponseTime -Average).Average
                Write-Host "      $dns ? $([math]::Round($latency))ms" -ForegroundColor White
            } else {
                Write-Host "      $dns ? SIN RESPUESTA" -ForegroundColor Red
            }
        }
    } else {
        Write-Host "   ? DNS Automático (del router)" -ForegroundColor Green
    }
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# 5. TEST DE PING A SERVIDORES DE FORTNITE
# ???????????????????????????????????????????????????????????????????

Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?? PING A SERVIDORES DE FORTNITE" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$fortniteServers = @{
    "NA-East (Virginia)" = "qosping-aws-us-east-1.ol.epicgames.com"
    "NA-West (Oregon)" = "qosping-aws-us-west-2.ol.epicgames.com"
    "EU-West (Irlanda)" = "qosping-aws-eu-west-1.ol.epicgames.com"
    "EU-Central (Frankfurt)" = "qosping-aws-eu-central-1.ol.epicgames.com"
    "Brazil" = "qosping-aws-sa-east-1.ol.epicgames.com"
    "Asia-Tokyo" = "qosping-aws-ap-northeast-1.ol.epicgames.com"
}

Write-Host "Testeando ping a servidores de Fortnite..." -ForegroundColor White
Write-Host "(Esto puede tomar 30-60 segundos)" -ForegroundColor Gray
Write-Host ""

foreach ($server in $fortniteServers.GetEnumerator()) {
    Write-Host "   ?? $($server.Key):" -ForegroundColor Cyan
    Write-Host "      $($server.Value)" -ForegroundColor Gray
    
    $ping = Test-Connection -ComputerName $server.Value -Count 4 -Quiet -ErrorAction SilentlyContinue
    if ($ping) {
        $result = Test-Connection -ComputerName $server.Value -Count 4 -ErrorAction SilentlyContinue
        if ($result) {
            $avg = ($result | Measure-Object -Property ResponseTime -Average).Average
            $min = ($result | Measure-Object -Property ResponseTime -Minimum).Minimum
            $max = ($result | Measure-Object -Property ResponseTime -Maximum).Maximum
            
            Write-Host "      Promedio: $([math]::Round($avg))ms | Min: $min ms | Max: $max ms" -ForegroundColor White
            
            if ($avg -lt 50) {
                Write-Host "      ? EXCELENTE LATENCIA" -ForegroundColor Green
            } elseif ($avg -lt 100) {
                Write-Host "      ? BUENA LATENCIA" -ForegroundColor Green
            } elseif ($avg -lt 150) {
                Write-Host "      ??  LATENCIA MODERADA" -ForegroundColor Yellow
            } else {
                Write-Host "      ? LATENCIA ALTA" -ForegroundColor Red
            }
        }
    } else {
        Write-Host "      ? SIN RESPUESTA" -ForegroundColor Red
    }
    Write-Host ""
}

