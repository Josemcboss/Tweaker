# ?? Testing Pre-Release - GHOST OPTIMIZER

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? TESTING PRE-RELEASE" -ForegroundColor Green
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$passed = 0
$failed = 0
$warnings = 0

# ???????????????????????????????????????
# 1. COMPILACIÓN
# ???????????????????????????????????????
Write-Host "1?? VERIFICANDO COMPILACIÓN" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray

try {
    $buildOutput = dotnet build -c Release --verbosity quiet 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Host "  ? Compilación: SUCCESS" -ForegroundColor Green
        $passed++
    } else {
        Write-Host "  ? Compilación: FAILED" -ForegroundColor Red
        $failed++
        Write-Host $buildOutput
    }
} catch {
    Write-Host "  ? Error: $_" -ForegroundColor Red
    $failed++
}

Write-Host ""

# ???????????????????????????????????????
# 2. ARCHIVOS CRÍTICOS
# ???????????????????????????????????????
Write-Host "2?? VERIFICANDO ARCHIVOS CRÍTICOS" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray

$criticalFiles = @(
    "MainWindow.xaml",
    "MainWindow.xaml.cs",
    "README_USER.md",
    "Publish.ps1"
)

foreach ($file in $criticalFiles) {
    if (Test-Path $file) {
        Write-Host "  ? $file" -ForegroundColor Green
        $passed++
    } else {
        Write-Host "  ? $file (FALTA)" -ForegroundColor Red
        $failed++
    }
}

Write-Host ""

# ???????????????????????????????????????
# 3. VERSIÓN CORRECTA
# ???????????????????????????????????????
Write-Host "3?? VERIFICANDO VERSIÓN" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray

$xamlContent = Get-Content "MainWindow.xaml" -Raw

if ($xamlContent -match "v2.0") {
    Write-Host "  ? Versión 2.0 en title bar" -ForegroundColor Green
    $passed++
} else {
    Write-Host "  ?? Versión no encontrada en title bar" -ForegroundColor Yellow
    $warnings++
}

$readmeContent = Get-Content "README_USER.md" -Raw

if ($readmeContent -match "v2.0" -or $readmeContent -match "2.0.0") {
    Write-Host "  ? Versión 2.0 en README" -ForegroundColor Green
    $passed++
} else {
    Write-Host "  ?? Versión no encontrada en README" -ForegroundColor Yellow
    $warnings++
}

Write-Host ""

# ???????????????????????????????????????
# 4. CARACTERÍSTICAS CLAVE
# ???????????????????????????????????????
Write-Host "4?? VERIFICANDO CARACTERÍSTICAS CLAVE" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray

$csContent = Get-Content "MainWindow.xaml.cs" -Raw

$features = @{
    "RevertAllTweaks" = "Botón Revertir Todo"
    "UpdateDashboard" = "Dashboard dinámico"
    "ProfileManager" = "Profile Manager"
    "BackupService" = "Backup Service"
    "NotificationService" = "Notificaciones"
}

foreach ($feature in $features.GetEnumerator()) {
    if ($csContent -match $feature.Key) {
        Write-Host "  ? $($feature.Value)" -ForegroundColor Green
        $passed++
    } else {
        Write-Host "  ? $($feature.Value) (FALTA)" -ForegroundColor Red
        $failed++
    }
}

Write-Host ""

# ???????????????????????????????????????
# 5. DOCUMENTACIÓN
# ???????????????????????????????????????
Write-Host "5?? VERIFICANDO DOCUMENTACIÓN" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray

$docs = @(
    "README_USER.md",
    "GITHUB_RELEASE_GUIDE.md",
    "CS8625_WARNINGS_FIXED.md"
)

foreach ($doc in $docs) {
    if (Test-Path $doc) {
        $size = (Get-Item $doc).Length
        if ($size -gt 100) {
            Write-Host "  ? $doc ($size bytes)" -ForegroundColor Green
            $passed++
        } else {
            Write-Host "  ?? $doc (muy pequeño: $size bytes)" -ForegroundColor Yellow
            $warnings++
        }
    } else {
        Write-Host "  ? $doc (FALTA)" -ForegroundColor Red
        $failed++
    }
}

Write-Host ""

# ???????????????????????????????????????
# 6. WARNINGS CS8625
# ???????????????????????????????????????
Write-Host "6?? VERIFICANDO WARNINGS CS8625" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????" -ForegroundColor Gray

if ($csContent -match "#nullable disable") {
    Write-Host "  ? #nullable disable presente" -ForegroundColor Green
    $passed++
} else {
    Write-Host "  ?? #nullable disable NO encontrado" -ForegroundColor Yellow
    $warnings++
}

Write-Host ""

# ???????????????????????????????????????
# RESUMEN
# ???????????????????????????????????????
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? RESUMEN DEL TEST" -ForegroundColor Green
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$total = $passed + $failed + $warnings

Write-Host "Tests Pasados:   $passed" -ForegroundColor Green
Write-Host "Tests Fallidos:  $failed" -ForegroundColor Red
Write-Host "Advertencias:    $warnings" -ForegroundColor Yellow
Write-Host "Total:           $total" -ForegroundColor Gray
Write-Host ""

if ($failed -eq 0 -and $warnings -eq 0) {
    Write-Host "????????????????????????????????????????" -ForegroundColor Green
    Write-Host "  ? LISTO PARA PUBLICAR" -ForegroundColor Green
    Write-Host "????????????????????????????????????????" -ForegroundColor Green
    Write-Host ""
    Write-Host "Próximos pasos:" -ForegroundColor White
    Write-Host "  1. Ejecutar Publish.ps1" -ForegroundColor Gray
    Write-Host "  2. Probar el ejecutable" -ForegroundColor Gray
    Write-Host "  3. Crear GitHub Release" -ForegroundColor Gray
    Write-Host "  4. Subir archivos ZIP" -ForegroundColor Gray
} elseif ($failed -eq 0) {
    Write-Host "????????????????????????????????????????" -ForegroundColor Yellow
    Write-Host "  ?? REVISAR ADVERTENCIAS" -ForegroundColor Yellow
    Write-Host "????????????????????????????????????????" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "Puedes publicar, pero revisa las advertencias arriba." -ForegroundColor Gray
} else {
    Write-Host "????????????????????????????????????????" -ForegroundColor Red
    Write-Host "  ? NO LISTO PARA PUBLICAR" -ForegroundColor Red
    Write-Host "????????????????????????????????????????" -ForegroundColor Red
    Write-Host ""
    Write-Host "Corrige los errores antes de publicar." -ForegroundColor Gray
}

Write-Host ""

# Calcular porcentaje de éxito
$successRate = if ($total -gt 0) { ($passed / $total) * 100 } else { 0 }

Write-Host "Tasa de éxito: $([math]::Round($successRate, 1))%" -ForegroundColor $(
    if ($successRate -ge 90) { "Green" }
    elseif ($successRate -ge 70) { "Yellow" }
    else { "Red" }
)

Write-Host ""
