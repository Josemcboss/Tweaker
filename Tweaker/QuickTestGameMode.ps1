# ???????????????????????????????????????????????????????????????????
# QUICK TEST: GAME MODE TWEAKS
# Verifica que los nuevos tweaks están funcionando correctamente
# ???????????????????????????????????????????????????????????????????

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? QUICK TEST: GAME MODE TWEAKS" -ForegroundColor Green
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Verificar permisos de administrador
$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

if (-not $isAdmin) {
    Write-Host "??  Ejecutando sin permisos de Administrador" -ForegroundColor Yellow
    Write-Host "   (Algunas verificaciones pueden fallar)" -ForegroundColor Gray
    Write-Host ""
}

$passCount = 0
$totalTests = 4

# ???????????????????????????????????????????????????????????????????
# TEST 1: Windows Game Mode
# ???????????????????????????????????????????????????????????????????

Write-Host "Test 1/4: Windows Game Mode..." -ForegroundColor Cyan

try {
    $gameModeKey = "HKCU:\SOFTWARE\Microsoft\GameBar"
    
    if (Test-Path $gameModeKey) {
        Write-Host "  ? PASS - Registry key existe" -ForegroundColor Green
        $passCount++
    } else {
        Write-Host "  ??  SKIP - Xbox Game Bar no instalado" -ForegroundColor Yellow
        Write-Host "     (Game Mode no disponible en este sistema)" -ForegroundColor Gray
    }
} catch {
    Write-Host "  ? FAIL - Error: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# TEST 2: NTFS Last Access Time
# ???????????????????????????????????????????????????????????????????

Write-Host "Test 2/4: NTFS Last Access Time..." -ForegroundColor Cyan

try {
    $ntfsResult = fsutil behavior query disablelastaccess 2>&1
    
    if ($ntfsResult -match "disablelastaccess") {
        Write-Host "  ? PASS - Comando fsutil funciona correctamente" -ForegroundColor Green
        $passCount++
    } else {
        Write-Host "  ? FAIL - No se pudo ejecutar fsutil" -ForegroundColor Red
    }
} catch {
    Write-Host "  ? FAIL - Error: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# TEST 3: Game Process Priority
# ???????????????????????????????????????????????????????????????????

Write-Host "Test 3/4: Game Process Priority..." -ForegroundColor Cyan

try {
    $imagePath = "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options"
    
    if (Test-Path $imagePath) {
        Write-Host "  ? PASS - Registry path accesible" -ForegroundColor Green
        $passCount++
        
        # Verificar si algún juego ya tiene configuración
        $testGame = "FortniteClient-Win64-Shipping.exe"
        $testPath = "$imagePath\$testGame\PerfOptions"
        
        if (Test-Path $testPath) {
            Write-Host "     ??  Fortnite ya tiene prioridad alta configurada" -ForegroundColor Cyan
        } else {
            Write-Host "     ??  Ningún juego configurado aún (esperado)" -ForegroundColor Gray
        }
    } else {
        Write-Host "  ? FAIL - No se puede acceder a registry path" -ForegroundColor Red
    }
} catch {
    Write-Host "  ? FAIL - Error: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# TEST 4: Transparency
# ???????????????????????????????????????????????????????????????????

Write-Host "Test 4/4: Transparency..." -ForegroundColor Cyan

try {
    $transparencyKey = "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Themes\Personalize"
    
    if (Test-Path $transparencyKey) {
        Write-Host "  ? PASS - Registry key existe" -ForegroundColor Green
        $passCount++
        
        $transparency = Get-ItemProperty -Path $transparencyKey -Name "EnableTransparency" -ErrorAction SilentlyContinue
        
        if ($transparency) {
            if ($transparency.EnableTransparency -eq 0) {
                Write-Host "     ??  Transparency actualmente DESHABILITADA" -ForegroundColor Cyan
            } else {
                Write-Host "     ??  Transparency actualmente HABILITADA" -ForegroundColor Gray
            }
        }
    } else {
        Write-Host "  ? FAIL - Registry key no encontrada" -ForegroundColor Red
    }
} catch {
    Write-Host "  ? FAIL - Error: $($_.Exception.Message)" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????????????????????????????????
# RESULTADO FINAL
# ???????????????????????????????????????????????????????????????????

Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? RESULTADO FINAL" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$percentage = [math]::Round(($passCount / $totalTests) * 100, 0)

Write-Host "Tests Pasados: $passCount/$totalTests ($percentage%)" -ForegroundColor White

if ($passCount -eq $totalTests) {
    Write-Host ""
    Write-Host "? TODOS LOS TESTS PASARON" -ForegroundColor Green
    Write-Host "   Los Game Mode Tweaks están funcionando correctamente" -ForegroundColor Gray
    Write-Host ""
    Write-Host "Próximo paso:" -ForegroundColor Cyan
    Write-Host "  1. Ejecuta Tweaker.exe (como Admin)" -ForegroundColor White
    Write-Host "  2. Ve a 'Sistema & GPU'" -ForegroundColor White
    Write-Host "  3. Scroll hasta '?? Game Mode & Optimizations'" -ForegroundColor White
    Write-Host "  4. Testea los botones ON/OFF" -ForegroundColor White
} elseif ($passCount -ge $totalTests * 0.5) {
    Write-Host ""
    Write-Host "??  TESTS PARCIALES" -ForegroundColor Yellow
    Write-Host "   Algunos componentes pueden no estar disponibles" -ForegroundColor Gray
    Write-Host "   (Esto es normal si no tienes Xbox Game Bar instalado)" -ForegroundColor Gray
} else {
    Write-Host ""
    Write-Host "? VARIOS TESTS FALLARON" -ForegroundColor Red
    Write-Host "   Posibles causas:" -ForegroundColor Yellow
    Write-Host "   • No ejecutado como Administrador" -ForegroundColor Gray
    Write-Host "   • Permisos de registry insuficientes" -ForegroundColor Gray
    Write-Host "   • Problemas con el sistema" -ForegroundColor Gray
}

Write-Host ""
Write-Host "????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

pause
