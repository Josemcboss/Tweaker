# ?? Test Rápido de Optimizaciones Avanzadas de Red
# Este script verifica el estado de las optimizaciones

Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? NETWORK OPTIMIZATION CHECKER" -ForegroundColor Green
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# ???????????????????????????????????????
# 1. MTU Verification
# ???????????????????????????????????????
Write-Host "1?? MTU (Maximum Transmission Unit)" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

$mtu = netsh interface ipv4 show subinterface | Select-String "Ethernet|Wi-Fi"
if ($mtu) {
    Write-Host $mtu -ForegroundColor White
    if ($mtu -match "1492") {
        Write-Host "? MTU optimizado (1492)" -ForegroundColor Green
    } else {
        Write-Host "?? MTU por defecto" -ForegroundColor Cyan
    }
} else {
    Write-Host "? No se pudo obtener MTU" -ForegroundColor Red
}
Write-Host ""

# ???????????????????????????????????????
# 2. Auto-Tuning Level
# ???????????????????????????????????????
Write-Host "2?? TCP Auto-Tuning y Features" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

$tcpGlobal = netsh interface tcp show global

# Auto-Tuning
$autoTuning = $tcpGlobal | Select-String "Receive Window Auto-Tuning Level"
Write-Host "Auto-Tuning: " -NoNewline
if ($autoTuning -match "normal") {
    Write-Host "? Normal (Optimizado)" -ForegroundColor Green
} else {
    Write-Host "?? $autoTuning" -ForegroundColor Cyan
}

# RSS
$rss = $tcpGlobal | Select-String "Receive-Side Scaling State"
Write-Host "RSS: " -NoNewline
if ($rss -match "enabled") {
    Write-Host "? Enabled" -ForegroundColor Green
} else {
    Write-Host "? Disabled" -ForegroundColor Red
}

# Chimney Offload
$chimney = $tcpGlobal | Select-String "Chimney Offload State"
Write-Host "Chimney Offload: " -NoNewline
if ($chimney -match "enabled") {
    Write-Host "? Enabled" -ForegroundColor Green
} else {
    Write-Host "? Disabled" -ForegroundColor Red
}

# NetDMA
$netdma = $tcpGlobal | Select-String "NetDMA State"
Write-Host "NetDMA: " -NoNewline
if ($netdma -match "enabled") {
    Write-Host "? Enabled" -ForegroundColor Green
} else {
    Write-Host "? Disabled" -ForegroundColor Red
}

# Timestamps
$timestamps = $tcpGlobal | Select-String "Timestamps"
Write-Host "TCP Timestamps: " -NoNewline
if ($timestamps -match "enabled") {
    Write-Host "? Enabled" -ForegroundColor Green
} else {
    Write-Host "? Disabled" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????
# 3. Congestion Control
# ???????????????????????????????????????
Write-Host "3?? Congestion Control" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

$congestion = $tcpGlobal | Select-String "Congestion Provider"
Write-Host "Provider: " -NoNewline
if ($congestion -match "ctcp") {
    Write-Host "? CTCP (Optimizado)" -ForegroundColor Green
} else {
    Write-Host "?? $congestion" -ForegroundColor Cyan
}

$ecn = $tcpGlobal | Select-String "ECN Capability"
Write-Host "ECN: " -NoNewline
if ($ecn -match "enabled") {
    Write-Host "? Enabled" -ForegroundColor Green
} else {
    Write-Host "? Disabled" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????
# 4. QoS Registry Values
# ???????????????????????????????????????
Write-Host "4?? QoS Configuration (Registry)" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

$tcpParams = "HKLM:\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters"

try {
    $nonBestEffort = Get-ItemProperty -Path $tcpParams -Name "NonBestEffortLimit" -ErrorAction SilentlyContinue
    if ($nonBestEffort.NonBestEffortLimit -eq 0) {
        Write-Host "NonBestEffortLimit: ? 0 (20% bandwidth liberado)" -ForegroundColor Green
    } else {
        Write-Host "NonBestEffortLimit: ?? Default" -ForegroundColor Cyan
    }
} catch {
    Write-Host "NonBestEffortLimit: ?? No configurado" -ForegroundColor Cyan
}

try {
    $disableUserTOS = Get-ItemProperty -Path $tcpParams -Name "DisableUserTOSSetting" -ErrorAction SilentlyContinue
    if ($null -ne $disableUserTOS) {
        Write-Host "DisableUserTOSSetting: ? Configurado ($($disableUserTOS.DisableUserTOSSetting))" -ForegroundColor Green
    } else {
        Write-Host "DisableUserTOSSetting: ?? No configurado" -ForegroundColor Cyan
    }
} catch {
    Write-Host "DisableUserTOSSetting: ?? No configurado" -ForegroundColor Cyan
}

Write-Host ""

# ???????????????????????????????????????
# 5. Adapter Advanced Settings
# ???????????????????????????????????????
Write-Host "5?? Adapter Advanced Settings (Registry)" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

try {
    $tcp1323 = Get-ItemProperty -Path $tcpParams -Name "Tcp1323Opts" -ErrorAction SilentlyContinue
    if ($tcp1323.Tcp1323Opts -eq 3) {
        Write-Host "Window Scaling: ? Enabled (3)" -ForegroundColor Green
    } else {
        Write-Host "Window Scaling: ?? Default" -ForegroundColor Cyan
    }
} catch {
    Write-Host "Window Scaling: ?? No configurado" -ForegroundColor Cyan
}

try {
    $sack = Get-ItemProperty -Path $tcpParams -Name "SackOpts" -ErrorAction SilentlyContinue
    if ($sack.SackOpts -eq 1) {
        Write-Host "SACK: ? Enabled" -ForegroundColor Green
    } else {
        Write-Host "SACK: ?? Default" -ForegroundColor Cyan
    }
} catch {
    Write-Host "SACK: ?? No configurado" -ForegroundColor Cyan
}

try {
    $retrans = Get-ItemProperty -Path $tcpParams -Name "TcpMaxDataRetransmissions" -ErrorAction SilentlyContinue
    if ($retrans.TcpMaxDataRetransmissions -eq 3) {
        Write-Host "Max Retransmissions: ? 3 (Optimizado)" -ForegroundColor Green
    } else {
        Write-Host "Max Retransmissions: ?? Default (5)" -ForegroundColor Cyan
    }
} catch {
    Write-Host "Max Retransmissions: ?? No configurado" -ForegroundColor Cyan
}

Write-Host ""

# ???????????????????????????????????????
# 6. Network Adapter Status
# ???????????????????????????????????????
Write-Host "6?? Network Adapter Status" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

$adapters = Get-NetAdapter | Where-Object {$_.Status -eq "Up"}
foreach ($adapter in $adapters) {
    Write-Host "?? $($adapter.Name)" -ForegroundColor Cyan
    Write-Host "   Interface: $($adapter.InterfaceDescription)" -ForegroundColor Gray
    Write-Host "   Speed: $($adapter.LinkSpeed)" -ForegroundColor White
    Write-Host "   Status: " -NoNewline
    if ($adapter.Status -eq "Up") {
        Write-Host "? Connected" -ForegroundColor Green
    } else {
        Write-Host "? Disconnected" -ForegroundColor Red
    }
    Write-Host ""
}

# ???????????????????????????????????????
# 7. Latency Test
# ???????????????????????????????????????
Write-Host "7?? Latency Test (Ping a 8.8.8.8)" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray
Write-Host "Ejecutando 10 pings..." -ForegroundColor Gray

$pingResult = Test-Connection -ComputerName 8.8.8.8 -Count 10 -Quiet
$pingStats = Test-Connection -ComputerName 8.8.8.8 -Count 10

if ($pingResult) {
    $avgLatency = ($pingStats | Measure-Object -Property ResponseTime -Average).Average
    Write-Host "Latencia promedio: " -NoNewline
    
    if ($avgLatency -lt 20) {
        Write-Host "$([math]::Round($avgLatency, 2)) ms ? Excelente" -ForegroundColor Green
    } elseif ($avgLatency -lt 50) {
        Write-Host "$([math]::Round($avgLatency, 2)) ms ? Bueno" -ForegroundColor Green
    } elseif ($avgLatency -lt 100) {
        Write-Host "$([math]::Round($avgLatency, 2)) ms ?? Aceptable" -ForegroundColor Yellow
    } else {
        Write-Host "$([math]::Round($avgLatency, 2)) ms ? Alto" -ForegroundColor Red
    }
} else {
    Write-Host "? No se pudo hacer ping" -ForegroundColor Red
}

Write-Host ""

# ???????????????????????????????????????
# 8. Resumen
# ???????????????????????????????????????
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  ?? RESUMEN" -ForegroundColor Green
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

Write-Host "Optimizaciones detectadas:" -ForegroundColor White
Write-Host ""

# Contar optimizaciones activas
$optimizationsActive = 0
$optimizationsTotal = 10

if ($mtu -match "1492") { $optimizationsActive++ }
if ($autoTuning -match "normal") { $optimizationsActive++ }
if ($rss -match "enabled") { $optimizationsActive++ }
if ($chimney -match "enabled") { $optimizationsActive++ }
if ($netdma -match "enabled") { $optimizationsActive++ }
if ($congestion -match "ctcp") { $optimizationsActive++ }
if ($ecn -match "enabled") { $optimizationsActive++ }
if ($null -ne $nonBestEffort -and $nonBestEffort.NonBestEffortLimit -eq 0) { $optimizationsActive++ }
if ($null -ne $tcp1323 -and $tcp1323.Tcp1323Opts -eq 3) { $optimizationsActive++ }
if ($null -ne $sack -and $sack.SackOpts -eq 1) { $optimizationsActive++ }

$percentage = [math]::Round(($optimizationsActive / $optimizationsTotal) * 100, 0)

Write-Host "Activas: " -NoNewline
if ($percentage -ge 80) {
    Write-Host "$optimizationsActive/$optimizationsTotal ($percentage%) ?" -ForegroundColor Green
} elseif ($percentage -ge 50) {
    Write-Host "$optimizationsActive/$optimizationsTotal ($percentage%) ??" -ForegroundColor Yellow
} else {
    Write-Host "$optimizationsActive/$optimizationsTotal ($percentage%) ?" -ForegroundColor Red
}

Write-Host ""
Write-Host "?? Recomendaciones:" -ForegroundColor Yellow
if ($percentage -lt 100) {
    Write-Host "   • Aplica las optimizaciones faltantes desde Tweaker" -ForegroundColor Gray
}
Write-Host "   • Reinicia Windows después de aplicar cambios" -ForegroundColor Gray
Write-Host "   • Verifica mejoras con speedtest antes/después" -ForegroundColor Gray
Write-Host ""

Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""
