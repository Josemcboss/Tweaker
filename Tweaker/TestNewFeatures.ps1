# ???????????????????????????????????????????????????????????????????
# FUNCIÓN: Test MPO Disable
# ???????????????????????????????????????????????????????????????????
function Test-MPODisable {
    Write-Host "?? TESTING MPO DISABLE..." -ForegroundColor Yellow
    Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
    
    try {
        $dwmPath = "HKLM:\SOFTWARE\Microsoft\Windows\Dwm"
        
        # Crear/Acceder a la clave
        if (-not (Test-Path $dwmPath)) {
            New-Item -Path $dwmPath -Force | Out-Null
            Write-Host "   ? Clave DWM creada"
        }
        
        # Establecer OverlayTestMode = 5
        Set-ItemProperty -Path $dwmPath -Name "OverlayTestMode" -Value 5 -Type DWord
        Write-Host "   ? OverlayTestMode = 5 establecido"
        
        # Verificar
        $verification = Get-ItemProperty -Path $dwmPath -Name "OverlayTestMode"
        if ($verification.OverlayTestMode -eq 5) {
            Write-Host "   ? VERIFICACIÓN EXITOSA: MPO deshabilitado correctamente" -ForegroundColor Green
            return $true
        } else {
            Write-Host "   ? VERIFICACIÓN FALLÓ: Valor = $($verification.OverlayTestMode)" -ForegroundColor Red
            return $false
        }
    } catch {
        Write-Host "   ? ERROR en test MPO disable: $($_.Exception.Message)" -ForegroundColor Red
        return $false
    }
}

