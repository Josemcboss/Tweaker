# FUNCIÓN: Test CPU Priority Profiles
# ???????????????????????????????????????????????????????????????????
function Test-CpuPriorityProfiles {
    Write-Host "?? TESTING CPU PRIORITY PROFILES..." -ForegroundColor Yellow
    Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
    
    $priorityPath = "HKLM:\SYSTEM\CurrentControlSet\Control\PriorityControl"
    $profiles = @{
        "Balanced" = 38
        "Smooth" = 40
        "Aggressive" = 22
        "Default" = 2
    }
    
    $allPassed = $true
    
    foreach ($profile in $profiles.GetEnumerator()) {
        try {
            Write-Host "   ?? Testing profile: $($profile.Key) (Value: $($profile.Value))"
            
            # Establecer valor
            Set-ItemProperty -Path $priorityPath -Name "Win32PrioritySeparation" -Value $profile.Value -Type DWord
            
            # Verificar
            $verification = Get-ItemProperty -Path $priorityPath -Name "Win32PrioritySeparation"
            
            if ($verification.Win32PrioritySeparation -eq $profile.Value) {
                Write-Host "      ? $($profile.Key): CORRECTO" -ForegroundColor Green
            } else {
                Write-Host "      ? $($profile.Key): FALLÓ - Esperado $($profile.Value), Got $($verification.Win32PrioritySeparation)" -ForegroundColor Red
                $allPassed = $false
            }
        } catch {
            Write-Host "      ? $($profile.Key): ERROR - $($_.Exception.Message)" -ForegroundColor Red
            $allPassed = $false
        }
    }
    
    return $allPassed
}

