# FUNCIÓN: Verificar Estado de MPO
# ???????????????????????????????????????????????????????????????????
function Test-MPOStatus {
    Write-Host "?? VERIFICANDO ESTADO ACTUAL DE MPO..." -ForegroundColor Yellow
    Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
    
    try {
        $dwmPath = "HKLM:\SOFTWARE\Microsoft\Windows\Dwm"
        
        if (Test-Path $dwmPath) {
            $overlayValue = Get-ItemProperty -Path $dwmPath -Name "OverlayTestMode" -ErrorAction SilentlyContinue
            
            if ($overlayValue) {
                $value = $overlayValue.OverlayTestMode
                Write-Host "   ?? Estado MPO: " -NoNewline
                
                switch ($value) {
                    5 { 
                        Write-Host "DESHABILITADO (Legacy Mode)" -ForegroundColor Green
                        Write-Host "   ?? OverlayTestMode = 5"
                        Write-Host "   ? MPO en modo legacy - Sin stuttering"
                    }
                    0 { 
                        Write-Host "HABILITADO EXPLÍCITAMENTE" -ForegroundColor Yellow
                        Write-Host "   ?? OverlayTestMode = 0" 
                        Write-Host "   ?? MPO forzado activo"
                    }
                    default { 
                        Write-Host "CONFIGURACIÓN CUSTOM ($value)" -ForegroundColor Magenta
                        Write-Host "   ?? OverlayTestMode = $value"
                        Write-Host "   ? Valor no estándar"
                    }
                }
            } else {
                Write-Host "   ?? Estado MPO: " -NoNewline
                Write-Host "WINDOWS DEFAULT (Habilitado)" -ForegroundColor Cyan
                Write-Host "   ?? OverlayTestMode no existe"
                Write-Host "   ?? Windows maneja MPO automáticamente"
            }
        } else {
            Write-Host "   ? ERROR: Clave DWM no encontrada" -ForegroundColor Red
        }
        
        return $true
    } catch {
        Write-Host "   ? ERROR verificando MPO: $($_.Exception.Message)" -ForegroundColor Red
        return $false
    }
}

