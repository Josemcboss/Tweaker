# ???????????????????????????????????????????????????????????????????
function Test-GeneralIntegrity {
    Write-Host "?? VERIFICANDO INTEGRIDAD GENERAL..." -ForegroundColor Yellow
    Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
    
    $issues = @()
    
    # Verificar claves críticas
    $criticalPaths = @{
        "DWM" = "HKLM:\SOFTWARE\Microsoft\Windows\Dwm"
        "PriorityControl" = "HKLM:\SYSTEM\CurrentControlSet\Control\PriorityControl"
    }
    
    foreach ($path in $criticalPaths.GetEnumerator()) {
        if (Test-Path $path.Value) {
            Write-Host "   ? Clave $($path.Key): EXISTS" -ForegroundColor Green
        } else {
            Write-Host "   ? Clave $($path.Key): MISSING" -ForegroundColor Red
            $issues += "Missing registry path: $($path.Value)"
        }
    }
    
    # Verificar permisos
    try {
        $testPath = "HKLM:\SOFTWARE\Microsoft\Windows\Dwm"
        $testValue = Get-ItemProperty -Path $testPath -Name "OverlayTestMode" -ErrorAction SilentlyContinue
        Write-Host "   ? Permisos de lectura: OK" -ForegroundColor Green
        
        # Test write
        Set-ItemProperty -Path $testPath -Name "_TestValue" -Value 999 -Type DWord -ErrorAction Stop
        Remove-ItemProperty -Path $testPath -Name "_TestValue" -ErrorAction SilentlyContinue
        Write-Host "   ? Permisos de escritura: OK" -ForegroundColor Green
    } catch {
        Write-Host "   ? Permisos insuficientes: $($_.Exception.Message)" -ForegroundColor Red
        $issues += "Insufficient registry permissions"
    }
    
    return $issues
}

