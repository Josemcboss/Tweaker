# FUNCIÓN: Test MPO Restore
# ???????????????????????????????????????????????????????????????????
function Test-MPORestore {
    Write-Host "?? TESTING MPO RESTORE..." -ForegroundColor Yellow
    Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
    
    try {
        $dwmPath = "HKLM:\SOFTWARE\Microsoft\Windows\Dwm"
        
        # Eliminar OverlayTestMode (restaurar default)
        Remove-ItemProperty -Path $dwmPath -Name "OverlayTestMode" -ErrorAction SilentlyContinue
        Write-Host "   ? OverlayTestMode eliminado"
        
        # Verificar que no existe
        $verification = Get-ItemProperty -Path $dwmPath -Name "OverlayTestMode" -ErrorAction SilentlyContinue
        if (-not $verification) {
            Write-Host "   ? VERIFICACIÓN EXITOSA: MPO restaurado a Windows default" -ForegroundColor Green
            return $true
        } else {
            Write-Host "   ? VERIFICACIÓN FALLÓ: OverlayTestMode sigue existiendo" -ForegroundColor Red
            return $false
        }
    } catch {
        Write-Host "   ? ERROR en test MPO restore: $($_.Exception.Message)" -ForegroundColor Red
        return $false
    }
}

