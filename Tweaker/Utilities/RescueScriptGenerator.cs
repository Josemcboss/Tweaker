using System;
using System.Diagnostics;
using System.IO;
using System.Text;

namespace Tweaker.Utilities
{
    /// <summary>
    /// GENERADOR DE SCRIPT DE RESCATE
    /// 
    /// ¿Por qué existe esta clase?
    /// ????????????????????????????????????????????????????????????????
    /// Si la aplicación causa un error crítico (ej: "Sihost.exe Unknown Hard Error"),
    /// el usuario puede quedar sin acceso a Windows normal.
    /// 
    /// SOLUCIÓN: Script de Rescate en el Escritorio
    /// ????????????????????????????????????????????????????????????????
    /// - Genera un archivo .bat con comandos de recuperación
    /// - El usuario puede ejecutarlo desde Modo Seguro
    /// - Reactiva servicios críticos y restaura BCD
    /// 
    /// UBICACIÓN: C:\Users\[Usuario]\Desktop\RESCATE_TWEAKER.bat
    /// 
    /// USO:
    /// ????????????????????????????????????????????????????????????????
    /// Si Windows no arranca:
    /// 1. Iniciar en Modo Seguro (F8 al bootear)
    /// 2. Ir al Escritorio
    /// 3. Ejecutar "RESCATE_TWEAKER.bat" como Administrador
    /// 4. Reiniciar
    /// </summary>
    public static class RescueScriptGenerator
    {
        /// <summary>
        /// GENERAR SCRIPT DE RESCATE EN EL ESCRITORIO
        /// ????????????????????????????????????????????????????????????????
        /// Llama a este método al iniciar la aplicación por primera vez.
        /// </summary>
        public static void GenerateRescueScript()
        {
            try
            {
                string desktopPath = Environment.GetFolderPath(Environment.SpecialFolder.Desktop);
                string rescueScriptPath = Path.Combine(desktopPath, "RESCATE_TWEAKER.bat");

                // No sobrescribir si ya existe
                if (File.Exists(rescueScriptPath))
                {
                    Debug.WriteLine($"?? Script de rescate ya existe: {rescueScriptPath}");
                    return;
                }

                StringBuilder script = new StringBuilder();

                // ???????????????????????????????????????????????????????????????
                // ENCABEZADO DEL SCRIPT
                // ???????????????????????????????????????????????????????????????

                script.AppendLine("@echo off");
                script.AppendLine(":: ???????????????????????????????????????????????????????????????");
                script.AppendLine(":: SCRIPT DE RESCATE - TWEAKER");
                script.AppendLine(":: ???????????????????????????????????????????????????????????????");
                script.AppendLine(":: Este script restaura servicios criticos y configuracion BCD");
                script.AppendLine(":: Ejecutar como ADMINISTRADOR desde Modo Seguro si Windows no arranca");
                script.AppendLine(":: ???????????????????????????????????????????????????????????????");
                script.AppendLine();
                script.AppendLine("echo.");
                script.AppendLine("echo ?????????????????????????????????????????????????????????????????");
                script.AppendLine("echo ?         SCRIPT DE RESCATE - GHOST OPTIMIZER TWEAKER          ?");
                script.AppendLine("echo ?????????????????????????????????????????????????????????????????");
                script.AppendLine("echo.");
                script.AppendLine("echo Este script restaurara:");
                script.AppendLine("echo   1. Servicios criticos de Windows");
                script.AppendLine("echo   2. Configuracion BCD predeterminada");
                script.AppendLine("echo.");
                script.AppendLine("pause");
                script.AppendLine();

                // ???????????????????????????????????????????????????????????????
                // PARTE 1: REACTIVAR SERVICIOS CRÍTICOS
                // ???????????????????????????????????????????????????????????????

                script.AppendLine("echo.");
                script.AppendLine("echo ???????????????????????????????????????????????????????????????");
                script.AppendLine("echo PARTE 1: REACTIVANDO SERVICIOS CRITICOS");
                script.AppendLine("echo ???????????????????????????????????????????????????????????????");
                script.AppendLine("echo.");
                script.AppendLine();

                // Servicios críticos que SIEMPRE deben estar activos
                string[] criticalServices = new[]
                {
                    "RpcSs",                    // Remote Procedure Call
                    "DcomLaunch",               // DCOM Server Process Launcher (CAUSA DE SIHOST.EXE ERROR)
                    "BrokerInfrastructure",     // Background Tasks Infrastructure
                    "LSM",                      // Local Session Manager
                    "SamSs",                    // Security Accounts Manager
                    "ProfSvc",                  // User Profile Service
                    "RpcEptMapper",             // RPC Endpoint Mapper
                    "gpsvc",                    // Group Policy Client
                    "CoreMessagingRegistrar",   // Core Messaging Broker
                    "SystemEventsBroker",       // System Events Broker
                    "StateRepository",          // State Repository Service
                    "Power",                    // Power Service
                    "EventLog",                 // Windows Event Log
                    "PlugPlay",                 // Plug and Play
                    "CryptSvc",                 // Cryptographic Services
                    "Themes",                   // Themes Service
                    "UserManager",              // User Manager
                    "Schedule",                 // Task Scheduler
                    "Dhcp",                     // DHCP Client (RED CRÍTICA)
                    "Dnscache",                 // DNS Client (RED CRÍTICA)
                };

                foreach (string serviceName in criticalServices)
                {
                    script.AppendLine($"echo Reactivando: {serviceName}...");
                    script.AppendLine($"sc config {serviceName} start= auto");
                    script.AppendLine($"net start {serviceName} 2>nul");
                    script.AppendLine();
                }

                // ???????????????????????????????????????????????????????????????
                // PARTE 2: RESTAURAR CONFIGURACIÓN BCD
                // ???????????????????????????????????????????????????????????????

                script.AppendLine("echo.");
                script.AppendLine("echo ???????????????????????????????????????????????????????????????");
                script.AppendLine("echo PARTE 2: RESTAURANDO CONFIGURACION BCD");
                script.AppendLine("echo ???????????????????????????????????????????????????????????????");
                script.AppendLine("echo.");
                script.AppendLine();

                // Restaurar HPET a default
                script.AppendLine("echo Restaurando timer de sistema (HPET)...");
                script.AppendLine("bcdedit /set useplatformclock true");
                script.AppendLine("bcdedit /set disabledynamictick no");
                script.AppendLine();

                // Restaurar Hyper-V a auto (default)
                script.AppendLine("echo Restaurando Hyper-V a modo automatico...");
                script.AppendLine("bcdedit /set hypervisorlaunchtype auto");
                script.AppendLine();

                // Restaurar otras opciones comunes de BCD a default
                script.AppendLine("echo Restaurando otras opciones de boot...");
                script.AppendLine("bcdedit /deletevalue tscsyncpolicy");
                script.AppendLine("bcdedit /deletevalue x2apicpolicy");
                script.AppendLine();

                // ???????????????????????????????????????????????????????????????
                // PARTE 3: CREAR PUNTO DE RESTAURACIÓN
                // ???????????????????????????????????????????????????????????????

                script.AppendLine("echo.");
                script.AppendLine("echo ???????????????????????????????????????????????????????????????");
                script.AppendLine("echo PARTE 3: CREANDO PUNTO DE RESTAURACION");
                script.AppendLine("echo ???????????????????????????????????????????????????????????????");
                script.AppendLine("echo.");
                script.AppendLine();

                script.AppendLine("echo Creando punto de restauracion del sistema...");
                script.AppendLine("powershell.exe -NoProfile -ExecutionPolicy Bypass -Command \"Checkpoint-Computer -Description 'Rescate Tweaker' -RestorePointType 'MODIFY_SETTINGS'\"");
                script.AppendLine();

                // ???????????????????????????????????????????????????????????????
                // FIN DEL SCRIPT
                // ???????????????????????????????????????????????????????????????

                script.AppendLine("echo.");
                script.AppendLine("echo ?????????????????????????????????????????????????????????????????");
                script.AppendLine("echo ?                    RESCATE COMPLETADO                        ?");
                script.AppendLine("echo ?????????????????????????????????????????????????????????????????");
                script.AppendLine("echo.");
                script.AppendLine("echo Servicios criticos reactivados.");
                script.AppendLine("echo Configuracion BCD restaurada a valores predeterminados.");
                script.AppendLine("echo.");
                script.AppendLine("echo IMPORTANTE:");
                script.AppendLine("echo   - REINICIA Windows ahora");
                script.AppendLine("echo   - Si el problema persiste, usa Restauracion del Sistema");
                script.AppendLine("echo   - Busca puntos de restauracion con \"Tweaker\" en el nombre");
                script.AppendLine("echo.");
                script.AppendLine("pause");

                // Escribir el archivo
                File.WriteAllText(rescueScriptPath, script.ToString(), Encoding.Default);

                Debug.WriteLine("???????????????????????????????????????????????????????????????");
                Debug.WriteLine("? SCRIPT DE RESCATE GENERADO");
                Debug.WriteLine("???????????????????????????????????????????????????????????????");
                Debug.WriteLine($"Ubicación: {rescueScriptPath}");
                Debug.WriteLine("");
                Debug.WriteLine("USO DEL SCRIPT:");
                Debug.WriteLine("  1. Si Windows no arranca, iniciar en Modo Seguro (F8)");
                Debug.WriteLine("  2. Ir al Escritorio");
                Debug.WriteLine("  3. Ejecutar 'RESCATE_TWEAKER.bat' como Administrador");
                Debug.WriteLine("  4. Reiniciar Windows");
                Debug.WriteLine("???????????????????????????????????????????????????????????????");
            }
            catch (Exception ex)
            {
                Debug.WriteLine($"?? Error generando script de rescate: {ex.Message}");
                Debug.WriteLine("   La aplicación continuará sin script de rescate");
            }
        }

        /// <summary>
        /// ABRIR EL SCRIPT DE RESCATE EN EL ESCRITORIO
        /// ????????????????????????????????????????????????????????????????
        /// Útil para mostrar al usuario dónde está el script.
        /// </summary>
        public static void OpenRescueScriptLocation()
        {
            try
            {
                string desktopPath = Environment.GetFolderPath(Environment.SpecialFolder.Desktop);
                Process.Start("explorer.exe", desktopPath);
                Debug.WriteLine($"?? Abriendo ubicación del script: {desktopPath}");
            }
            catch (Exception ex)
            {
                Debug.WriteLine($"?? Error abriendo ubicación: {ex.Message}");
            }
        }
    }
}
