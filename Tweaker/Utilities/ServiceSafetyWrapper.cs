using Microsoft.Win32;
using System;
using System.Diagnostics;
using System.ServiceProcess;
using Tweaker.Utilities;

namespace Tweaker.Optimizations
{
    /// <summary>
    /// CAPA DE SEGURIDAD ADICIONAL - SERVICE SAFETY WRAPPER
    /// 
    /// ¿Por qué existe esta clase?
    /// ????????????????????????????????????????????????????????????????
    /// Después del incidente donde Sihost.exe falló a pesar de ServiceGuard,
    /// se implementó esta capa EXTRA de validación que actúa como FIREWALL
    /// antes de CUALQUIER modificación de servicios.
    /// 
    /// DIFERENCIAS con ServiceGuard:
    /// ????????????????????????????????????????????????????????????????
    /// ServiceGuard: Lista estática de servicios protegidos
    /// ServiceSafetyWrapper: Validación DINÁMICA + Verificación de estado actual
    /// 
    /// VALIDACIONES ADICIONALES:
    /// ????????????????????????????????????????????????????????????????
    /// 1. ? ServiceGuard (lista blanca estática)
    /// 2. ? Verificación de dependencias (servicios que dependen del target)
    /// 3. ? Verificación de estado actual (si está corriendo, probablemente es crítico)
    /// 4. ? Log exhaustivo de TODOS los intentos
    /// 5. ? Backup obligatorio antes de modificar
    /// 
    /// SEVERIDAD: CRÍTICO - NO MODIFICAR SIN AUTORIZACIÓN
    /// </summary>
    public static class ServiceSafetyWrapper
    {
        /// <summary>
        /// MODIFICAR SERVICIO DE FORMA ULTRA SEGURA
        /// ????????????????????????????????????????????????????????????????
        /// Wrapper que agrega múltiples capas de validación antes de modificar un servicio.
        /// 
        /// PARÁMETROS:
        /// - serviceName: Nombre del servicio (ej: "SysMain")
        /// - displayName: Nombre para mostrar (ej: "SysMain (Superfetch)")
        /// - newStartType: 2 = Automatic, 3 = Manual, 4 = Disabled
        /// - shouldStop: Si debe detener el servicio también
        /// 
        /// RETORNA:
        /// - true: Operación exitosa y segura
        /// - false: Operación bloqueada por seguridad
        /// </thinking>

        /// </summary>
        public static bool SafeModifyService(
            string serviceName, 
            string displayName, 
            int newStartType, 
            bool shouldStop = false)
        {
            Debug.WriteLine("???????????????????????????????????????????????????????????????");
            Debug.WriteLine($"?? SERVICE SAFETY WRAPPER - Intentando modificar: {displayName}");
            Debug.WriteLine("???????????????????????????????????????????????????????????????");

            // ???????????????????????????????????????????????????????????????
            // VALIDACIÓN 1: ServiceGuard (Lista Blanca)
            // ???????????????????????????????????????????????????????????????
            
            if (ServiceGuard.IsProtected(serviceName))
            {
                Debug.WriteLine($"? BLOQUEADO POR SERVICEGUARD: {serviceName}");
                Debug.WriteLine("   Este servicio está en la lista de protección.");
                
                // Registrar intento bloqueado en auditoría
                ServiceModificationAuditor.LogModificationAttempt(
                    serviceName,
                    operationType: newStartType == 4 ? "Disable" : "Modify",
                    wasBlocked: true,
                    reason: "Servicio protegido por ServiceGuard"
                );
                
                return false;
            }

            Debug.WriteLine($"? Validación 1: ServiceGuard permite modificar {serviceName}");

            // ???????????????????????????????????????????????????????????????
            // VALIDACIÓN 2: Verificar Dependencias
            // ???????????????????????????????????????????????????????????????
            
            if (HasCriticalDependents(serviceName))
            {
                Debug.WriteLine($"? BLOQUEADO POR DEPENDENCIAS: {serviceName}");
                Debug.WriteLine("   Servicios críticos dependen de este servicio.");
                return false;
            }

            Debug.WriteLine($"? Validación 2: Sin dependencias críticas");

            // ???????????????????????????????????????????????????????????????
            // VALIDACIÓN 3: Verificar si el servicio existe
            // ???????????????????????????????????????????????????????????????
            
            try
            {
                using (ServiceController sc = new ServiceController(serviceName))
                {
                    var status = sc.Status; // Lanza excepción si no existe
                    Debug.WriteLine($"? Validación 3: Servicio existe. Estado actual: {status}");
                }
            }
            catch (InvalidOperationException)
            {
                Debug.WriteLine($"?? Servicio {serviceName} no encontrado. Operación cancelada.");
                return false;
            }

            // ???????????????????????????????????????????????????????????????
            // VALIDACIÓN 4: Backup del valor actual (OBLIGATORIO)
            // ???????????????????????????????????????????????????????????????
            
            string registryPath = $@"SYSTEM\CurrentControlSet\Services\{serviceName}";
            bool backupSuccess = OptimizationBackup.BackupRegistryValue(registryPath, "Start");
            
            if (!backupSuccess)
            {
                Debug.WriteLine($"?? No se pudo hacer backup de {serviceName}. Continuando con precaución...");
            }
            else
            {
                Debug.WriteLine($"? Validación 4: Backup realizado exitosamente");
            }

            // ???????????????????????????????????????????????????????????????
            // VALIDACIÓN 5: Confirmación de operación
            // ???????????????????????????????????????????????????????????????
            
            string operationType = newStartType switch
            {
                2 => "AUTOMATIC",
                3 => "MANUAL",
                4 => "DISABLED",
                _ => "UNKNOWN"
            };

            Debug.WriteLine("???????????????????????????????????????????????????????????????");
            Debug.WriteLine("?? MODIFICACIÓN AUTORIZADA:");
            Debug.WriteLine($"   Servicio: {displayName} ({serviceName})");
            Debug.WriteLine($"   Nueva configuración: {operationType} ({newStartType})");
            Debug.WriteLine($"   Detener servicio: {(shouldStop ? "SÍ" : "NO")}");
            Debug.WriteLine("???????????????????????????????????????????????????????????????");

            // ???????????????????????????????????????????????????????????????
            // EJECUCIÓN: Detener servicio (si se solicitó)
            // ???????????????????????????????????????????????????????????????
            
            if (shouldStop)
            {
                try
                {
                    using (ServiceController sc = new ServiceController(serviceName))
                    {
                        if (sc.Status == ServiceControllerStatus.Running)
                        {
                            Debug.WriteLine($"?? Deteniendo servicio: {displayName}...");
                            sc.Stop();
                            sc.WaitForStatus(ServiceControllerStatus.Stopped, TimeSpan.FromSeconds(10));
                            Debug.WriteLine($"? Servicio detenido exitosamente");
                        }
                    }
                }
                catch (Exception ex)
                {
                    Debug.WriteLine($"?? No se pudo detener {displayName}: {ex.Message}");
                    Debug.WriteLine("   Continuando con modificación de registro...");
                }
            }

            // ???????????????????????????????????????????????????????????????
            // EJECUCIÓN: Modificar registro
            // ???????????????????????????????????????????????????????????????
            
            try
            {
                using (RegistryKey key = Registry.LocalMachine.OpenSubKey(registryPath, true))
                {
                    if (key == null)
                    {
                        Debug.WriteLine($"? No se encontró la clave de registro: {registryPath}");
                        return false;
                    }

                    // Obtener valor actual para logging
                    object currentValue = key.GetValue("Start");
                    Debug.WriteLine($"   Valor actual: Start = {currentValue}");

                    // Modificar
                    key.SetValue("Start", newStartType, RegistryValueKind.DWord);
                    
                    Debug.WriteLine($"   Nuevo valor: Start = {newStartType}");
                    Debug.WriteLine($"? Registro modificado exitosamente");
                }

                Debug.WriteLine("???????????????????????????????????????????????????????????????");
                Debug.WriteLine($"? OPERACIÓN COMPLETADA: {displayName}");
                Debug.WriteLine("???????????????????????????????????????????????????????????????");

                // Registrar modificación exitosa en auditoría
                ServiceModificationAuditor.LogModificationAttempt(
                    serviceName,
                    operationType: operationType,
                    wasBlocked: false,
                    reason: "Modificación autorizada y completada"
                );

                return true;
            }
            catch (Exception ex)
            {
                Debug.WriteLine("???????????????????????????????????????????????????????????????");
                Debug.WriteLine($"? ERROR MODIFICANDO REGISTRO: {displayName}");
                Debug.WriteLine($"   Excepción: {ex.Message}");
                Debug.WriteLine("???????????????????????????????????????????????????????????????");
                return false;
            }
        }

        /// <summary>
        /// VERIFICAR SI EL SERVICIO TIENE DEPENDIENTES CRÍTICOS
        /// ????????????????????????????????????????????????????????????????
        /// Verifica si otros servicios críticos dependen del servicio objetivo.
        /// 
        /// EJEMPLO:
        /// Si quieres deshabilitar "RpcSs", pero "DcomLaunch" depende de él,
        /// esta función retornará true y bloqueará la operación.
        /// </summary>
        private static bool HasCriticalDependents(string serviceName)
        {
            try
            {
                using (ServiceController sc = new ServiceController(serviceName))
                {
                    var dependents = sc.DependentServices;
                    
                    if (dependents == null || dependents.Length == 0)
                        return false;

                    Debug.WriteLine($"?? Dependientes de {serviceName}:");
                    
                    foreach (var dependent in dependents)
                    {
                        Debug.WriteLine($"   - {dependent.ServiceName}: {dependent.Status}");
                        
                        // Si algún dependiente es crítico, bloquear
                        if (ServiceGuard.IsProtected(dependent.ServiceName))
                        {
                            Debug.WriteLine($"      ?? CRÍTICO: Este servicio depende de {serviceName}");
                            return true;
                        }
                    }
                }

                return false;
            }
            catch (Exception ex)
            {
                Debug.WriteLine($"?? Error verificando dependientes: {ex.Message}");
                // En caso de error, asumir que tiene dependencias críticas (más seguro)
                return true;
            }
        }

        /// <summary>
        /// MÉTODO WRAPPER: Deshabilitar servicio de forma segura
        /// </summary>
        public static bool SafeDisableService(string serviceName, string displayName)
        {
            return SafeModifyService(serviceName, displayName, 4, shouldStop: true);
        }

        /// <summary>
        /// MÉTODO WRAPPER: Habilitar servicio de forma segura
        /// </summary>
        public static bool SafeEnableService(string serviceName, string displayName)
        {
            bool modified = SafeModifyService(serviceName, displayName, 2, shouldStop: false);
            
            if (modified)
            {
                // Intentar iniciar el servicio
                try
                {
                    using (ServiceController sc = new ServiceController(serviceName))
                    {
                        if (sc.Status != ServiceControllerStatus.Running)
                        {
                            Debug.WriteLine($"?? Iniciando servicio: {displayName}...");
                            sc.Start();
                            sc.WaitForStatus(ServiceControllerStatus.Running, TimeSpan.FromSeconds(10));
                            Debug.WriteLine($"? Servicio iniciado exitosamente");
                        }
                    }
                }
                catch (Exception ex)
                {
                    Debug.WriteLine($"?? No se pudo iniciar {displayName}: {ex.Message}");
                }
            }

            return modified;
        }

        /// <summary>
        /// OBTENER ESTADO ACTUAL DE UN SERVICIO (Para debugging)
        /// </summary>
        public static string GetServiceInfo(string serviceName)
        {
            try
            {
                using (ServiceController sc = new ServiceController(serviceName))
                {
                    string registryPath = $@"SYSTEM\CurrentControlSet\Services\{serviceName}";
                    int startType = 0;

                    using (RegistryKey key = Registry.LocalMachine.OpenSubKey(registryPath, false))
                    {
                        if (key != null)
                        {
                            object value = key.GetValue("Start");
                            if (value != null)
                                startType = (int)value;
                        }
                    }

                    string startTypeStr = startType switch
                    {
                        2 => "AUTOMATIC",
                        3 => "MANUAL",
                        4 => "DISABLED",
                        _ => $"UNKNOWN ({startType})"
                    };

                    return $"{serviceName}: Status={sc.Status}, StartType={startTypeStr}";
                }
            }
            catch (Exception ex)
            {
                return $"{serviceName}: ERROR - {ex.Message}";
            }
        }
    }
}
