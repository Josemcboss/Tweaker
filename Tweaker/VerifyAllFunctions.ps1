    Write-Host "?? $($category.Name)" -ForegroundColor Magenta
    
    foreach ($test in $category.Group) {
        if ($test.Present) {
            Write-Host "   ? $($test.Function)" -ForegroundColor Green
            $presentFunctions++
        } else {
            if ($test.Critical) {
                Write-Host "   ? $($test.Function) [CRÍTICO]" -ForegroundColor Red
                $criticalMissing += $test.Function
            } else {
                Write-Host "   ?? $($test.Function) [OPCIONAL]" -ForegroundColor Yellow
                $nonCriticalMissing += $test.Function
            }
        }
    }
    Write-Host ""
}

