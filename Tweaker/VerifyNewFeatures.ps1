# ?? Verificación Rápida de Nuevas Características
# Ejecutar después de iniciar la aplicación

Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host "   ?? VERIFICACIÓN DE CARACTERÍSTICAS" -ForegroundColor Green
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Variables
$profilesPath = "$env:LOCALAPPDATA\Tweaker\Profiles"
$backupsPath = "$env:LOCALAPPDATA\Tweaker\Backups"

# ???????????????????????????????????????
# 1. Verificar ProfileManager
# ???????????????????????????????????????
Write-Host "?? VERIFICACIÓN DE PROFILE MANAGER" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

if (Test-Path $profilesPath) {
    Write-Host "? Directorio de perfiles existe: $profilesPath" -ForegroundColor Green
    
    $profiles = Get-ChildItem $profilesPath -Filter "*.tweakerprofile"
    Write-Host "?? Perfiles encontrados: $($profiles.Count)" -ForegroundColor White
    
    if ($profiles.Count -eq 5) {
        Write-Host "? Todos los perfiles predefinidos creados (5/5)" -ForegroundColor Green
    } else {
        Write-Host "?? Se esperaban 5 perfiles, encontrados: $($profiles.Count)" -ForegroundColor Yellow
    }
    
    Write-Host ""
    foreach ($profile in $profiles) {
        $content = Get-Content $profile.FullName | ConvertFrom-Json
        Write-Host "  ?? $($content.Name)" -ForegroundColor Cyan
        Write-Host "     Categoría: $($content.Category)" -ForegroundColor Gray
        Write-Host "     Tweaks: $($content.Tweaks.PSObject.Properties.Count)" -ForegroundColor Gray
        Write-Host "     Tamaño: $([math]::Round($profile.Length / 1KB, 2)) KB" -ForegroundColor Gray
        Write-Host ""
    }
} else {
    Write-Host "? Directorio de perfiles NO existe" -ForegroundColor Red
    Write-Host "   Ejecuta la aplicación primero" -ForegroundColor Yellow
}

# ???????????????????????????????????????
# 2. Verificar BackupService
# ???????????????????????????????????????
Write-Host "?? VERIFICACIÓN DE BACKUP SERVICE" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????" -ForegroundColor Gray

if (Test-Path $backupsPath) {
    Write-Host "? Directorio de backups existe: $backupsPath" -ForegroundColor Green
    
    $backups = Get-ChildItem $backupsPath -Filter "*.json"
    Write-Host "?? Backups encontrados: $($backups.Count)" -ForegroundColor White
    
    if ($backups.Count -gt 0) {
        Write-Host ""
        foreach ($backup in $backups | Select-Object -First 5) {
            $content = Get-Content $backup.FullName | ConvertFrom-Json
            Write-Host "  ?? $($content.Name)" -ForegroundColor Cyan
            Write-Host "     Creado: $($content.CreatedAt)" -ForegroundColor Gray
            Write-Host "     Tweaks: $($content.Tweaks.Count)" -ForegroundColor Gray
            Write-Host "     Tamaño: $([math]::Round($backup.Length / 1KB, 2)) KB" -ForegroundColor Gray
            Write-Host ""
        }
    } else {
        Write-Host "?? No hay backups creados todavía" -ForegroundColor Cyan
        Write-Host "   Usa la aplicación para crear uno" -ForegroundColor Gray
    }
} else {
    Write-Host "? Directorio de backups NO existe" -ForegroundColor Red
    Write-Host "   Ejecuta la aplicación primero" -ForegroundColor Yellow
}

# ???????????????????????????????????????
# 3. Resumen
# ???????????????????????????????????????
Write-Host ""
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host "   ?? RESUMEN" -ForegroundColor Green
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan

$profilesOk = Test-Path $profilesPath
$backupsOk = Test-Path $backupsPath
$profileCount = if ($profilesOk) { (Get-ChildItem $profilesPath -Filter "*.tweakerprofile").Count } else { 0 }
$backupCount = if ($backupsOk) { (Get-ChildItem $backupsPath -Filter "*.json").Count } else { 0 }

Write-Host ""
Write-Host "ProfileManager:" -ForegroundColor White
Write-Host "  Estado: $(if ($profilesOk) { '? Funcional' } else { '? No inicializado' })" -ForegroundColor $(if ($profilesOk) { 'Green' } else { 'Red' })
Write-Host "  Perfiles: $profileCount/5" -ForegroundColor White

Write-Host ""
Write-Host "BackupService:" -ForegroundColor White
Write-Host "  Estado: $(if ($backupsOk) { '? Funcional' } else { '? No inicializado' })" -ForegroundColor $(if ($backupsOk) { 'Green' } else { 'Red' })
Write-Host "  Backups: $backupCount" -ForegroundColor White

Write-Host ""

# ???????????????????????????????????????
# 4. Acciones Rápidas
# ???????????????????????????????????????
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host "   ?? ACCIONES RÁPIDAS" -ForegroundColor Green
Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

Write-Host "Comandos disponibles:" -ForegroundColor White
Write-Host ""
Write-Host "  # Abrir directorio de perfiles" -ForegroundColor Gray
Write-Host "  explorer `"$profilesPath`"" -ForegroundColor Yellow
Write-Host ""
Write-Host "  # Abrir directorio de backups" -ForegroundColor Gray
Write-Host "  explorer `"$backupsPath`"" -ForegroundColor Yellow
Write-Host ""
Write-Host "  # Ver contenido de un perfil" -ForegroundColor Gray
Write-Host "  Get-Content `"$profilesPath\MaximumPerformance.tweakerprofile`" | ConvertFrom-Json | Format-List" -ForegroundColor Yellow
Write-Host ""
Write-Host "  # Ejecutar aplicación" -ForegroundColor Gray
Write-Host "  dotnet run" -ForegroundColor Yellow
Write-Host ""

Write-Host "???????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""
